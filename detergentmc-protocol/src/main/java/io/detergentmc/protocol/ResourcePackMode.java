package io.detergentmc.protocol;

import java.util.Locale;

/**
 * Decides how the resource pack is offered to clients, from the
 * {@code resource-pack} section of {@code detergentmc.yml}.
 *
 * <p>Two modes exist:
 *
 * <ul>
 *   <li><b>Loopback (default):</b> {@code resource-pack.url} is empty.
 *       DetergentMC generates the demo pack with
 *       {@link ResourcePackBuilder} and serves it over HTTP on
 *       {@code 127.0.0.1} via {@link ResourcePackServer}. This is the
 *       only mode that works without any public hosting, and it is the
 *       default because no public hosting location has been chosen yet.
 *       </li>
 *   <li><b>External:</b> {@code resource-pack.url} starts with
 *       {@code https://}. No local HTTP server is started; the
 *       configured URL and SHA-1 are handed to the vanilla server
 *       as-is, through {@code server.properties}
 *       ({@code resource-pack} / {@code resource-pack-sha1}).
 *       {@code http://} URLs — and any other scheme — are refused:
 *       Minecraft clients only accept packs over HTTPS from a public
 *       host (plain HTTP is only allowed for loopback), so the decision
 *       falls back to loopback and carries a warning for the log.
 *       </li>
 * </ul>
 *
 * <h2>SHA-1 の検証方法 / How the SHA-1 is verified</h2>
 *
 * <p><b>Loopback:</b> the pack is generated locally, so its SHA-1 is
 * computed from the generated bytes and checked again when the HTTP
 * server starts ({@link ResourcePackServer#start()} re-hashes the file
 * and refuses to serve on a mismatch). The value is always
 * self-consistent.
 *
 * <p><b>External:</b> DetergentMC <em>never</em> downloads the hosted
 * file and <em>never</em> compares the configured SHA-1 against the
 * locally generated pack. The operator is responsible for putting the
 * exact zip file at {@code url} and writing that file's SHA-1 into
 * {@code resource-pack.sha1} (for example with
 * {@code sha1sum detergentmc-pack.zip}). Comparing against the local
 * pack would be wrong: the hosted file may legitimately differ from
 * the local demo pack (a custom pack, or a newer build of it). If the
 * configured SHA-1 does not match the hosted file, the Minecraft
 * client itself rejects the pack when it downloads it — the server
 * cannot detect that in advance, so a wrong SHA-1 only shows up on
 * the client side. When the hosted file changes, update the SHA-1 in
 * {@code detergentmc.yml} at the same time.
 *
 * <p>What DetergentMC <em>does</em> check for an external pack is only
 * the shape of the value: it must be 40 hexadecimal characters
 * ({@link #isValidSha1(String)}). A missing or malformed SHA-1 means
 * the pack cannot be offered: with {@code required=false} the server
 * starts without a pack (and logs a warning), and with
 * {@code required=true} the server refuses to start at all.
 *
 * <h2>1.20.1 variant (external mode)</h2>
 *
 * <p>External mode can also carry a 1.20.1 pack, configured with
 * {@code resource-pack.url-763} and {@code resource-pack.sha1-763}
 * (both optional). When both are valid, the proxy offers that pack to
 * 763 clients instead of the 1.20.4 pack; when they are missing or
 * invalid, a warning is logged and 763 clients are offered the 1.20.4
 * pack as before (which a 1.20.1 client shows as incompatible). The
 * 763 settings never change the primary pack's decision, and they never
 * make a required pack fail startup on their own — the primary
 * {@code url}/{@code sha1} still decide that.
 *
 * <h2>1.20.2 variant (external mode)</h2>
 *
 * <p>The same holds for a 1.20.2 pack, configured with
 * {@code resource-pack.url-764} and {@code resource-pack.sha1-764}.
 * The 1.20.2 pack must be {@code pack_format} 18 — the 1.20.1 pack
 * (format 15) is <em>not</em> shared with 764 clients, because a
 * 1.20.2 client shows a format-15 pack as incompatible. When the
 * 764 settings are missing or invalid, a warning is logged and 764
 * clients are offered the 1.20.4 pack as before.
 *
 * <h2>1.20.5 / 1.20.6 variant (external mode)</h2>
 *
 * <p>The same holds for a 1.20.5 / 1.20.6 pack, configured with
 * {@code resource-pack.url-766} and {@code resource-pack.sha1-766}.
 * One pack serves both versions: they share protocol 766. The pack
 * must be {@code pack_format} 32 — the 1.20.4 pack (format 22) is
 * <em>not</em> shared with 766 clients, because a 1.20.5 client shows
 * a format-22 pack as incompatible. When the 766 settings are missing
 * or invalid, a warning is logged and 766 clients are offered the
 * 1.20.4 pack as before.
 *
 * <h2>1.21 / 1.21.1 variant (external mode)</h2>
 *
 * <p>The same holds for a 1.21 / 1.21.1 pack, configured with
 * {@code resource-pack.url-767} and {@code resource-pack.sha1-767}.
 * One pack serves both versions: they share protocol 767. The pack
 * must be {@code pack_format} 34 — the 1.20.5 pack (format 32) is
 * <em>not</em> shared with 767 clients, because a 1.21 client shows
 * a format-32 pack as incompatible. When the 767 settings are missing
 * or invalid, a warning is logged and 767 clients are offered the
 * 1.20.4 pack as before.
 */
