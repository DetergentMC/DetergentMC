    /**
     * Returns {@code true} when {@code sha1} is a 40-character
     * hexadecimal SHA-1 (upper- or lower-case; it is normalized to
     * lower-case when a pack is built from it).
     */
    public static boolean isValidSha1(String sha1) {
        if (sha1 == null) {
            return false;
        }
        String value = sha1.trim();
        if (value.length() != 40) {
            return false;
        }
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            boolean hex = (c >= '0' && c <= '9')
                    || (c >= 'a' && c <= 'f')
                    || (c >= 'A' && c <= 'F');
            if (!hex) {
                return false;
            }
        }
        return true;
    }

    /**
     * Decides the delivery mode from the configured URL and SHA-1.
     *
     * <ul>
     *   <li>Empty (or blank) URL: loopback, no problem.</li>
     *   <li>{@code https://} URL with a valid SHA-1: external, with the
     *       pack to offer.</li>
     *   <li>{@code https://} URL with a missing or malformed SHA-1:
     *       external, but with no pack — the caller must not offer one
     *       (see the class javadoc for what happens next).</li>
     *   <li>Any other non-empty URL (including {@code http://}):
     *       refused, falls back to loopback, with a warning.</li>
     * </ul>
     *
     * @param configuredUrl    {@code resource-pack.url} (may be null/blank)
     * @param configuredSha1   {@code resource-pack.sha1} (may be null/blank)
     * @param required         {@code resource-pack.required}
     * @param promptKey        {@code resource-pack.prompt-key}; blank means
     *                         the default prompt
     */
    public static Decision decide(String configuredUrl, String configuredSha1,
            boolean required, String promptKey) {
        return decide(configuredUrl, configuredSha1, null, null, null, null, null, null, required, promptKey);
    }

